const PDFDocument = require("pdfkit");
const nodemailer = require("nodemailer");

const createEmailTransporter = () => {
    const emailUser = process.env.EMAIL_USER;
    const emailPass = process.env.EMAIL_PASS;

    if (!emailUser || !emailPass) {
        return null;
    }

    return nodemailer.createTransport({
        host: process.env.EMAIL_HOST || "smtp.gmail.com",
        port: Number(process.env.EMAIL_PORT) || 587,
        secure: String(process.env.EMAIL_SECURE || "false") === "true",
        auth: {
            user: emailUser,
            pass: emailPass.replace(/\s+/g, ""),
        },
    });
};

const generateTripPdfBuffer = (user, trip) => {
    return new Promise((resolve, reject) => {
        try {
            const doc = new PDFDocument({ margin: 40 });
            const buffers = [];

            doc.on("data", (chunk) => buffers.push(chunk));
            doc.on("end", () => resolve(Buffer.concat(buffers)));
            doc.on("error", (err) => reject(err));

            // Header
            doc.fontSize(22).fillColor("#0f172a").text("TripAI Travel Planner", { align: "center" });
            doc.moveDown(0.3);
            doc.fontSize(14).fillColor("#2563eb").text(`Trip Itinerary: ${trip.destination || "Upcoming Trip"}`, { align: "center" });
            doc.moveDown(0.8);

            // Horizontal Rule
            doc.strokeColor("#cbd5e1").lineWidth(1).moveTo(40, doc.y).lineTo(570, doc.y).stroke();
            doc.moveDown(0.8);

            // Traveler Details
            doc.fontSize(11).fillColor("#334155");
            doc.text(`Traveler: ${user.name || "Valued Traveler"} (${user.email || ""})`);
            const startDateStr = trip.startDate ? new Date(trip.startDate).toLocaleDateString() : "—";
            const endDateStr = trip.endDate ? new Date(trip.endDate).toLocaleDateString() : "—";
            doc.text(`Dates: ${startDateStr} to ${endDateStr}`);
            doc.text(`Travelers: ${trip.travelers || 1}`);
            doc.text(`Budget: ${trip.currency || "USD"} ${trip.budget || 0}`);
            doc.text(`Travel Style: ${trip.travelStyle || "balanced"}`);
            if (Array.isArray(trip.interests) && trip.interests.length > 0) {
                doc.text(`Interests: ${trip.interests.join(", ")}`);
            }
            doc.moveDown(1);

            // Itinerary
            doc.fontSize(14).fillColor("#0f172a").text("Day-by-Day Plan", { underline: true });
            doc.moveDown(0.5);

            if (Array.isArray(trip.itinerary) && trip.itinerary.length > 0) {
                trip.itinerary.forEach((dayPlan, index) => {
                    const dayNum = dayPlan.day || index + 1;
                    const dayDate = dayPlan.date ? ` (${new Date(dayPlan.date).toLocaleDateString()})` : "";
                    const dayTitle = dayPlan.title || `Day ${dayNum}`;

                    doc.fontSize(12).fillColor("#1e293b").text(`Day ${dayNum}${dayDate}: ${dayTitle}`, { bold: true });

                    if (Array.isArray(dayPlan.activities) && dayPlan.activities.length > 0) {
                        dayPlan.activities.forEach((act) => {
                            const timeStr = act.time ? `[${act.time}] ` : "";
                            const actTitle = act.title || (typeof act === "string" ? act : "Activity");
                            const actDesc = act.description ? ` - ${act.description}` : "";
                            const actLoc = act.location ? ` (@ ${act.location})` : "";

                            doc.fontSize(10).fillColor("#475569").text(`  • ${timeStr}${actTitle}${actLoc}${actDesc}`, {
                                indent: 10,
                                lineGap: 2,
                            });
                        });
                    }
                    doc.moveDown(0.5);
                });
            } else {
                doc.fontSize(10).fillColor("#64748b").text("No detailed day-by-day activities recorded yet.");
            }

            doc.moveDown(1.5);
            doc.fontSize(9).fillColor("#94a3b8").text("Generated by TripAI Travel Planner. Safe travels!", { align: "center" });

            doc.end();
        } catch (error) {
            reject(error);
        }
    });
};

const sendTripConfirmationEmail = async (user, trip) => {
    const transporter = createEmailTransporter();

    if (!transporter) {
        throw new Error("Email service is not configured. Set EMAIL_USER and EMAIL_PASS in the backend environment.");
    }

    if (!user || !user.email) {
        throw new Error("User email is required to send confirmation email.");
    }

    const pdfBuffer = await generateTripPdfBuffer(user, trip);
    const fromAddress = process.env.EMAIL_FROM || process.env.EMAIL_USER;
    const destinationName = trip.destination || "Your Trip";

    const mailOptions = {
        from: fromAddress,
        to: user.email,
        subject: `Your TripAI Itinerary: ${destinationName}`,
        html: `
            <div style="font-family: Arial, sans-serif; line-height: 1.6; color: #1f2937;">
                <h2 style="color: #0f172a; margin-bottom: 8px;">Your Trip to ${destinationName} is Saved!</h2>
                <p>Hello ${user.name || "Traveler"},</p>
                <p>We've attached your complete trip itinerary PDF to this email.</p>
                <div style="background: #f8fafc; border-left: 4px solid #2563eb; padding: 12px 16px; margin: 16px 0;">
                    <p style="margin: 0;"><strong>Destination:</strong> ${destinationName}</p>
                    <p style="margin: 4px 0 0 0;"><strong>Budget:</strong> ${trip.currency || "USD"} ${trip.budget || 0}</p>
                </div>
                <p>Have a wonderful trip!</p>
                <p style="color: #64748b; font-size: 13px; margin-top: 24px;">— The TripAI Team</p>
            </div>
        `,
        attachments: [
            {
                filename: `${destinationName.replace(/[^a-zA-Z0-9_-]/g, "_")}_Itinerary.pdf`,
                content: pdfBuffer,
                contentType: "application/pdf",
            },
        ],
    };

    const delivery = await transporter.sendMail(mailOptions);

    if (delivery.rejected.includes(user.email) || delivery.accepted.length === 0) {
        throw new Error("SMTP server did not accept the recipient email.");
    }

    return delivery;
};

module.exports = { sendTripConfirmationEmail, generateTripPdfBuffer };

